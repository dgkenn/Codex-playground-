#!/usr/bin/env python3
"""E168 — E165's constructive Challenge A test, judged against a floor that is actually a null.

REGISTERED BEFORE ANY FLOOR HAS BEEN COMPUTED. One repair, with the reason written down (rule 58).

=========================================================================================================
WHAT WAS WRONG WITH E165, IN ONE PARAGRAPH
=========================================================================================================
E165 asked the right question — is there a linear combination of the amplitude family that discriminates
conscious from unconscious while its ANAESTHETIC discrimination sits at the floor? — and then compared the
answer against a bar that was not a null. Its G3 took the agent legibility of **random projections** of the
feature matrix, 200 draws, 95th percentile **0.4203**, and required the adversarial arm to come in below
that. A random projection of eleven correlated features is a very poor predictor of anything, so 0.4203 is
a statement about random projections and not about chance: the corresponding **case-level permutation null
on the same cohort is around 0.19** (E161's machinery on the sibling VitalDB contrast). The verdict fired
at lam = 0 — with no adversarial pressure applied at all — which is what a vacuous bar looks like. E165's
result was recorded and NOT claimed, and error-catalogue rule 75 was written from it.

**The single repair here is the floor**: the agent label is permuted ACROSS CASES and pushed through the
ENTIRE pipeline — the leave-one-case-out adversarial fit and the held-out scoring — so the null is
generated by the same procedure that generated the observed value. Nothing else about the design moves:
same cohort, same features, same lambdas, same fit, same held-out evaluation, same acceptance condition.
Rule 58 allows one repair with a stated reason; this is it, and if the answer is still uninformative the
run is over.

=========================================================================================================
WHY THE FOLDED STATISTIC MAKES THIS NECESSARY RATHER THAN MERELY TIDIER
=========================================================================================================
`legibility` is `auc_abs - 0.5`, a FOLDED statistic, and rule 46 records that a folded statistic is biased
upward under the null. Its null centre is therefore NOT zero and cannot be reasoned about — with 39 cases
split roughly 23/16 the null mean is some positive number that has to be measured. This is precisely the
case where "the observed value is small, so it must be at chance" is unavailable, and it is why the whole
verdict has to rest on a measured distribution.

=========================================================================================================
GATES
=========================================================================================================
G1  MANIFEST, unchanged from E165: >= 12 cases per agent arm.

G2  **THE TWO NULLS MUST AGREE AT lam = 0, AND THIS CAN FAIL.** At lam = 0 the objective does not use the
    agent label at all, so the fitted projection is independent of it and the exact null can be obtained
    by permuting the label at SCORING time only — thousands of draws, essentially free. The full-pipeline
    permutation must reproduce that same distribution at lam = 0. If the two disagree beyond Monte Carlo
    error, the pipeline permutation is broken and nothing downstream is reported. This is the rule-40
    check applied to the repair itself: the new floor is validated against a floor computed a different
    way, not merely asserted to be better.

G3  **THE FLOOR, MEASURED PER LAMBDA.** For each lam, `N_PERM` case-level permutations of the agent label
    are pushed through fit and score; the floor is the 95th percentile of the resulting held-out agent
    legibility. Monte Carlo error on that percentile is reported beside it (rule 46) so a verdict decided
    by a margin smaller than its own noise is visible as such.

G4  **THE STATE AXIS MUST BE ALIVE**, or there is nothing to protect. Held-out state legibility at lam = 0
    must exceed its own permutation floor, built by flipping the conscious/unconscious assignment WITHIN
    case — the destruction that matches that estimand (rule 55), since the state contrast is paired.

=========================================================================================================
PRIMARY — THE UNINFORMATIVE AND WRONG-DIRECTION CASES ARE ENUMERATED FIRST (rules 31, 37)
=========================================================================================================
  (1) NOT INTERPRETABLE   G2 fails, or G4 fails. Nothing is reported about any lambda.
  (2) VACUOUS             the observed agent legibility at lam = 0 is ALREADY at or below the lam = 0
                          floor. Then the amplitude family does not leak the anaesthetic in this cohort
                          to begin with, no adversarial pressure was needed, and the experiment cannot
                          speak to whether pressure would work. **This is the outcome E165 actually had
                          and mislabelled**, and naming it in advance is the point of writing it here.
  (3) ENTANGLED           no lam gives BOTH held-out state legibility >= 80 % of the lam = 0 axis AND
                          held-out agent legibility at or below that lam's floor. The registered
                          prediction, inherited from E165 and from E161's seven-of-ten leakage table.
  (4) SEPARABLE           some lam gives both. The first constructed Challenge A candidate, and it must
                          then be carried to the VitalDB agent contrast before it is called anything.

REGISTERED PREDICTION, unchanged from E165 and still against the constructive hope: **(3) ENTANGLED.**
Stated with a qualification E165 could not state, because it had no floor: if the lam = 0 agent legibility
turns out to be at its own floor, the correct reading is **(2)**, and (2) is not a weaker version of (4) —
it means this cohort's agent contrast (27 pure-propofol against 16 MIXED-agent cases, not propofol against
sevoflurane) is too weak to pose the problem, and the test must move to VitalDB where E161 measured real
leakage.

SCOPE. Linear combinations, one deposit, spectra only, 39 cases, and an agent contrast that is
pure-versus-mixed rather than drug-versus-drug. Everything E165's scope paragraph says still applies.

    python bsde/src/bsde/experiments/e168_adversarial_with_permutation_floor.py [--perm N]
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..")))
sys.path.insert(0, HERE)

from e165_adversarial_challenge_a import (FEATURES, LAMBDAS, MIN_PER_ARM, STATE_TOL,  # noqa: E402
                                          build, evaluate, fit_w, legibility, ranks)

RESULTS = os.path.abspath(os.path.join(HERE, "..", "..", "..", "results"))
OUT = os.path.join(RESULTS, "e168_adversarial_permutation_floor.json")
SEED = 20260801
N_PERM = 100
EXACT_DRAWS = 5000


def evaluate_with_arm(cases, ids, lam, arm_override, seed=0):
    """E165's `evaluate`, with the agent vector supplied rather than read from the cases.

    Written out rather than monkey-patched so the permutation is visible in the diff, and structurally
    identical to E165's — the only difference is where `arm` comes from.
    """
    arm = np.asarray(arm_override, float)
    n_ids = len(ids)
    both = np.column_stack([ranks([cases[c][f"con_{f}"] for c in ids]
                                  + [cases[c][f"unc_{f}"] for c in ids]) for f in FEATURES])
    S, U = both[:n_ids], both[n_ids:]
    Xs = np.vstack([S, U])
    ys = np.concatenate([np.full(n_ids, -1.0), np.full(n_ids, 1.0)])
    ya = (arm - arm.mean()) / (arm.std() + 1e-12)
    st, ag = np.full(2 * n_ids, np.nan), np.full(n_ids, np.nan)
    for i in range(n_ids):
        tr = np.array([j for j in range(n_ids) if j != i])
        trs = np.concatenate([tr, tr + n_ids])
        w = fit_w(Xs[trs], ys[trs], U[tr], ya[tr], lam, seed=seed)
        st[i], st[i + n_ids] = S[i] @ w, U[i] @ w
        ag[i] = U[i] @ w
    state_lab = np.concatenate([np.zeros(n_ids), np.ones(n_ids)])
    return legibility(st, state_lab), legibility(ag, arm), st, ag


def mc_error_p95(sample, reps=400, rng=None):
    """Monte Carlo sd of the 95th percentile, by resampling the null draws (rule 46)."""
    rng = rng or np.random.default_rng(0)
    s = np.asarray(sample, float)
    s = s[np.isfinite(s)]
    if s.size < 20:
        return float("nan")
    return float(np.std([np.quantile(rng.choice(s, s.size, replace=True), 0.95) for _ in range(reps)]))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--perm", type=int, default=N_PERM)
    a = ap.parse_args(argv)
    rng = np.random.default_rng(SEED)

    cases = build()
    ids = sorted(cases)
    arm = np.array([cases[c]["arm"] for c in ids], float)
    n_mix, n_pro = int(arm.sum()), int((1 - arm).sum())
    res = {"experiment": "E168", "n_cases": len(ids), "n_mixed": n_mix, "n_propofol": n_pro,
           "lambdas": list(LAMBDAS), "n_perm": a.perm}
    g1 = n_mix >= MIN_PER_ARM and n_pro >= MIN_PER_ARM
    res["G1_pass"] = bool(g1)
    print(f"E168 — E165 judged against a permutation floor")
    print(f"G1 MANIFEST  {len(ids)} cases: {n_pro} pure propofol, {n_mix} mixed   "
          f"{'PASS' if g1 else '*** FAIL'}")
    if not g1:
        res["verdict"] = "GATE-FAILED"
        json.dump(res, open(OUT, "w"), indent=2)
        return 1

    # ---------------------------------------------------------------- observed, per lambda
    print("\nOBSERVED (E165's numbers, recomputed here so nothing is carried across by hand -- rule 59)")
    obs = {}
    for lam in LAMBDAS:
        t0 = time.time()
        s, g, st, ag = evaluate_with_arm(cases, ids, lam, arm, seed=0)
        obs[lam] = {"state": float(s), "agent": float(g), "ag": ag.tolist(), "st": st.tolist()}
        print(f"   lam={lam:<4.1f} state {s:+.4f}   agent {g:+.4f}   ({time.time() - t0:.1f} s)")
    res["observed"] = {str(k): {"state": v["state"], "agent": v["agent"]} for k, v in obs.items()}

    # ---------------------------------------------------------------- G2: exact vs pipeline null at lam=0
    ag0 = np.asarray(obs[0.0]["ag"], float)
    exact = []
    for _ in range(EXACT_DRAWS):
        exact.append(legibility(ag0, rng.permutation(arm)))
    exact = np.asarray([e for e in exact if math.isfinite(e)])
    ex_p95 = float(np.quantile(exact, 0.95))
    print(f"\nG2 exact lam=0 null (label permuted at SCORING only, the fit never saw it): "
          f"{exact.size} draws, mean {exact.mean():.4f}, p95 {ex_p95:.4f}")

    print(f"   full-pipeline null at lam=0, {a.perm} draws (must reproduce the exact one)...")
    pipe0 = []
    for k in range(a.perm):
        _, g, _, _ = evaluate_with_arm(cases, ids, 0.0, rng.permutation(arm), seed=0)
        if math.isfinite(g):
            pipe0.append(g)
    pipe0 = np.asarray(pipe0)
    pi_p95 = float(np.quantile(pipe0, 0.95))
    mc0 = mc_error_p95(pipe0, rng=rng)
    agree = abs(pi_p95 - ex_p95) <= 3 * max(mc0, 1e-9)
    res["G2"] = {"exact_mean": float(exact.mean()), "exact_p95": ex_p95,
                 "pipeline_mean": float(pipe0.mean()), "pipeline_p95": pi_p95,
                 "pipeline_mc_sd": mc0, "pass": bool(agree)}
    print(f"   pipeline: mean {pipe0.mean():.4f}, p95 {pi_p95:.4f} (MC sd {mc0:.4f})   "
          f"{'PASS -- the two nulls agree' if agree else '*** FAIL -- the pipeline permutation is broken'}")

    # ---------------------------------------------------------------- G4: is the state axis alive?
    st0 = np.asarray(obs[0.0]["st"], float)
    n = len(ids)
    snull = []
    for _ in range(EXACT_DRAWS):
        flip = rng.integers(0, 2, n).astype(bool)      # WITHIN case: swap that case's con/unc assignment
        lab = np.concatenate([flip.astype(float), 1.0 - flip.astype(float)])
        snull.append(legibility(st0, lab))
    snull = np.asarray([s for s in snull if math.isfinite(s)])
    s_p95 = float(np.quantile(snull, 0.95))
    g4 = obs[0.0]["state"] > s_p95
    res["G4"] = {"state_lam0": obs[0.0]["state"], "floor_p95": s_p95, "pass": bool(g4)}
    print(f"\nG4 state axis alive: lam=0 state {obs[0.0]['state']:+.4f} vs within-case flip floor "
          f"{s_p95:+.4f}   {'PASS' if g4 else '*** FAIL'}")

    if not (res["G2"]["pass"] and g4):
        res["verdict"] = "NOT-INTERPRETABLE"
        res["why"] = ("G2 or G4 failed: either the pipeline permutation does not reproduce the exact null, "
                      "or there is no state axis to protect")
        print("\nVERDICT NOT INTERPRETABLE — " + res["why"])
        json.dump(res, open(OUT, "w"), indent=2)
        return 1

    # ---------------------------------------------------------------- G3: the floor, per lambda
    print(f"\nG3 FLOOR per lambda, {a.perm} case-level permutations pushed through fit AND score")
    floors = {0.0: {"p95": pi_p95, "mean": float(pipe0.mean()), "mc_sd": mc0, "n": int(pipe0.size)}}
    for lam in LAMBDAS:
        if lam == 0.0:
            continue
        t0, draws = time.time(), []
        for _ in range(a.perm):
            _, g, _, _ = evaluate_with_arm(cases, ids, lam, rng.permutation(arm), seed=0)
            if math.isfinite(g):
                draws.append(g)
        d = np.asarray(draws)
        floors[lam] = {"p95": float(np.quantile(d, 0.95)), "mean": float(d.mean()),
                       "mc_sd": mc_error_p95(d, rng=rng), "n": int(d.size)}
        print(f"   lam={lam:<4.1f} floor p95 {floors[lam]['p95']:+.4f} "
              f"(mean {floors[lam]['mean']:+.4f}, MC sd {floors[lam]['mc_sd']:.4f}, "
              f"{d.size} draws, {time.time() - t0:.0f} s)")
    res["floors"] = {str(k): v for k, v in floors.items()}

    # ---------------------------------------------------------------- verdict
    print(f"\n{'lam':>5s} {'state':>9s} {'>= 80% of lam0':>15s} {'agent':>9s} {'floor':>9s} "
          f"{'at floor':>9s}")
    s0 = obs[0.0]["state"]
    rows, sep = [], []
    for lam in LAMBDAS:
        st_ok = obs[lam]["state"] >= STATE_TOL * s0
        ag_ok = obs[lam]["agent"] <= floors[lam]["p95"]
        rows.append({"lam": lam, "state": obs[lam]["state"], "state_ok": bool(st_ok),
                     "agent": obs[lam]["agent"], "floor": floors[lam]["p95"], "agent_ok": bool(ag_ok)})
        if st_ok and ag_ok:
            sep.append(lam)
        print(f"{lam:>5.1f} {obs[lam]['state']:>+9.4f} {str(st_ok):>15s} "
              f"{obs[lam]['agent']:>+9.4f} {floors[lam]['p95']:>+9.4f} {str(ag_ok):>9s}")
    res["rows"] = rows

    vacuous = obs[0.0]["agent"] <= floors[0.0]["p95"]
    if vacuous:
        v = "VACUOUS"
        why = ("the lam = 0 state axis is ALREADY at its agent floor "
               f"({obs[0.0]['agent']:+.4f} vs {floors[0.0]['p95']:+.4f}), so the amplitude family does not "
               "leak the anaesthetic in this cohort and no adversarial pressure was needed. This is the "
               "outcome E165 had and mislabelled. The test must move to VitalDB, where E161 measured real "
               "leakage in seven of ten features.")
    elif not sep:
        v = "ENTANGLED"
        why = ("no lambda keeps 80 % of the state axis while reaching its own permutation floor: state and "
               "agent information are entangled in the linear span of the amplitude family")
    else:
        v = "SEPARABLE"
        why = (f"lambda in {sep} keeps >= {STATE_TOL:.0%} of the state axis with agent legibility at its "
               "own floor; this must now be carried to the VitalDB agent contrast before it is called "
               "anything")
    res["verdict"], res["why"], res["separable_lambdas"] = v, why, sep
    print(f"\nVERDICT {v} — {why}")
    json.dump(res, open(OUT, "w"), indent=2)
    print(f"\nwrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
