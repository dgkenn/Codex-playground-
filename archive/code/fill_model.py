#!/usr/bin/env python3
"""fill_model.py -- Maker fill-probability estimator for the Polymarket weekly-crypto SHORT-VOL edge.

WHAT THIS IS
------------
The confirmed edge (node PMKT-SHORTVOL-LONGSHOT) is a MAKER strategy: rest an offer to SELL YES on far-OTM
weekly "BTC/ETH above $X on <date>?" markets when YES is in [0.15,0.30], entering in the FIRST HALF of the
market's life, holding to UMA resolution. Backtest / print study earn ~+0.12/ct (trade-weighted). The #1
pre-live risk is EXECUTION: the trade-flow study found a resting seller only gets in-band fillable YES-buy
flow in ~26% of weekly markets (74% see ZERO in-band taker flow). Raw edge means nothing on an order that
never fills. This module estimates the REALISTIC maker-fill probability and the honest fill-adjusted capture.

ARCHITECTURE (adapted from braedonsaunders/homerun's Cox proportional-hazards FILL MODEL)
-----------------------------------------------------------------------------------------
homerun trains a Cox PH model P(fill within Delta-t) on its OWN historical order fills, with covariates
{queue depth ahead/behind, spread, recent trade intensity, time-to-resolution, side imbalance, vol, latency},
and returns THREE fill estimates per order (pessimistic / realistic / optimistic) instead of one.

We have NO L2 queue history (Polymarket public data is trade prints only), so we CANNOT observe queue depth.
We ADAPT the pattern using only observable proxies from real trade prints:
  * trade intensity  -> in-band YES-BUY taker arrival rate (shares/hr) during the first-half window
  * spread / touch    -> price distance of our resting offer from the band; only takers paying >= our ask fill us
  * time-to-resolution-> weekly horizon (days) and elapsed fraction of the first-half window
  * queue position    -> UNOBSERVABLE. Collapsed into a single scenario knob phi = fraction of eligible
                         arriving flow WE capture (1 = alone at the touch; <1 = we share the book / sit behind
                         other resting sellers). phi is the dominant unknown; the pess/real/opt ENSEMBLE is
                         generated by proportional-hazards scaling in phi (capture fraction is literally a
                         multiplier on the fill hazard), exactly homerun's 3-estimate idea.

MECHANICS OF A FILL (fully observable, no L2 needed)
----------------------------------------------------
We rest SELL YES, size S shares, at ask price p (in band). A retail taker BUYS YES from us (lifts our offer)
only if willing to pay >= p. Each historical in-band YES-BUY print at yes_price q >= p is a taker who WOULD
have lifted a resting offer at p. So:
    eligible base flow  B(p)   = sum of in-band first-half YES-BUY shares with yes_price >= p
    our captured flow          = phi * B(p)               (queue-competition haircut)
    fill_shares                = min(S, phi * B(p))
    fill_fraction              = fill_shares / S
    fully_filled               = 1[ phi * B(p) >= S ]
    captured PnL (maker)       = fill_shares * (p - outcome)     outcome in {0,1}, zero fee (+small rebate)
Time-to-fill: walk the eligible arrivals in time order; fill_time = first t at which cumulative phi*arrivals
reaches S (else censored at window end). This is a real marked point process from real prints.

There is a genuine EDGE-vs-CAPACITY frontier: resting cheaper (p -> 0.15) captures ALL band flow but earns
almost nothing per contract (realized YES ~0.14, so edge ~ p-0.14); resting richer (p -> 0.30) earns more
per fill but sees far less eligible flow. The study's "all in-band flow at +0.12/ct" is the (p=band-floor,
phi=1) OPTIMISTIC corner of this frontier; this model prices the whole surface.

OUTPUTS
-------
fill_model_report.md, fill_model_summary.json, and the reusable FillModel class + fill_probability() function
for the go-live sizing layer:  fill_probability(order_size, features, scenario) -> {pess, real, opt}.

DISCIPLINE: real prints only; phi (queue competition) is UNOBSERVABLE and is the key assumption -- a full
sensitivity table over phi is reported so the reader can reprice. Thin per-market print counts (median ~6
in-band prints) are flagged. The fill-adjusted capture is LOWER than the raw edge, as expected.
"""
