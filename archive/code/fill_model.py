# ---- frozen strategy constants (identical to the confirmed edge; NOT retuned) ----
BAND_LO, BAND_HI = 0.15, 0.30
MIN_HORIZON_DAYS, MAX_HORIZON_DAYS = 4.0, 10.0
FIRST_HALF = 0.5

# ---- ensemble scenario knob: phi = fraction of eligible arriving flow we capture (queue proxy) ----
# phi is UNOBSERVABLE (no L2 queue data). These are assumptions; full sensitivity over phi is reported.
PHI = {"pessimistic": 0.15, "realistic": 0.35, "optimistic": 0.65}
PHI_THEORETICAL_CEIL = 1.00   # lone maker at the touch, captures 100% of eligible flow (upper bound)
PHI_SENS = [0.10, 0.15, 0.25, 0.35, 0.50, 0.75, 1.00]

# resting-price grid for the edge-vs-capacity frontier
PRICE_GRID = [0.15, 0.18, 0.20, 0.22, 0.25, 0.28]
OPERATING_PRICE = 0.20    # headline operating point: near band floor -> high fill, still positive per-ct edge
# order-size grid (shares) for the fill-probability curve
SIZE_GRID = [5, 10, 25, 50, 100, 250, 500, 1000, 2500]


# ============================================================ data reconstruction (offline, cached)
def _iso(s):
    try:
        return datetime.fromisoformat(str(s).replace("Z", "+00:00"))
    except Exception:
        return None


def _asset(q):
    ql = (q or "").lower()
    if "bitcoin" in ql or "btc" in ql:
        return "BTC"
    if "ethereum" in ql or "eth" in ql:
        return "ETH"
    return "?"


def _iso_week(ts):
    y, w, _ = datetime.fromtimestamp(ts, tz=timezone.utc).isocalendar()
    return f"{y}-W{w:02d}"


def _trade_file(cond):
    fn = cond.replace("0x", "") + ".json"
    for d in (TCACHE_NEW, TCACHE_OLD):
        p = os.path.join(d, fn)
        if os.path.exists(p):
            return p
    return None


def yes_price(t):
    return t["price"] if t["outcome"] == "Yes" else 1.0 - t["price"]


def is_yes_long(t):
    # a resting maker SELLING YES is filled by aggressive YES-LONG takers
    return (t["side"] == "BUY" and t["outcome"] == "Yes") or (t["side"] == "SELL" and t["outcome"] == "No")


def build_market_index():
    """Enumerate settled weekly (4-10d) BTC/ETH 'above $X' markets from the cached gamma events. Offline."""
    mkts, seen = [], set()
    for f in sorted(glob.glob(os.path.join(EVCACHE, "*.json"))):
        try:
            ev = json.load(open(f))
        except Exception:
            continue
        if not ev or not ev.get("markets"):
            continue
        for m in ev.get("markets", []):
            q = m.get("question", "")
            if "above" not in q.lower():
                continue
            s, e = _iso(m.get("startDate")), _iso(m.get("endDate"))
            if not s or not e:
                continue
            hd = (e - s).total_seconds() / 86400.0
            if not (MIN_HORIZON_DAYS <= hd <= MAX_HORIZON_DAYS):
                continue
            if not m.get("closed"):
                continue
            try:
                op = json.loads(m.get("outcomePrices") or "[]")
                yr = float(op[0])
            except Exception:
                continue
            if yr not in (0.0, 1.0):
                continue
            cond = m.get("conditionId")
            if not cond or cond in seen:
                continue
            seen.add(cond)
            mkts.append(dict(cond=cond, asset=_asset(q), start=s.timestamp(), end=e.timestamp(),
                             horizon_days=hd, yes_outcome=int(yr), week=_iso_week(e.timestamp())))
    return mkts


def reconstruct_arrivals(force=False):
    """Per market, reconstruct the in-band first-half YES-BUY arrival process (real prints). Cached to pickle.

    Returns list of dicts with: cond, asset, week, yes_outcome, horizon_days, window_hours,
      arrivals = sorted list of (t_frac_of_window, size, yes_price)  for in-band first-half YES-BUY prints,
      total in-band shares/dollars, and per-price-threshold cumulative eligible shares.
    """
    if os.path.exists(ARR_PICKLE) and not force:
        with open(ARR_PICKLE, "rb") as f:
            return pickle.load(f)
    idx = build_market_index()
    out = []
    for m in idx:
        tf = _trade_file(m["cond"])
        if not tf:
            continue
        try:
            tr = json.load(open(tf))["trades"]
        except Exception:
            continue
        start, end = m["start"], m["end"]
        ehalf = start + FIRST_HALF * (end - start)
        win = max(ehalf - start, 1.0)
        arr = []
        for t in tr:
            ts = t.get("ts")
            if ts is None:
                continue
            if start <= ts <= ehalf and is_yes_long(t) and BAND_LO <= yes_price(t) <= BAND_HI:
                arr.append(((ts - start) / win, float(t["size"]), yes_price(t)))
        arr.sort()
        ib_shares = sum(a[1] for a in arr)
        ib_dollars = sum(a[1] * a[2] for a in arr)
        out.append(dict(cond=m["cond"], asset=m["asset"], week=m["week"],
                        yes_outcome=m["yes_outcome"], horizon_days=m["horizon_days"],
                        window_hours=win / 3600.0, arrivals=arr,
                        ib_shares=ib_shares, ib_dollars=ib_dollars,
                        vwap=(ib_dollars / ib_shares if ib_shares > 0 else None)))
    with open(ARR_PICKLE, "wb") as f:
        pickle.dump(out, f)
    return out


# ============================================================ core fill mechanics
def eligible_base(arrivals, p):
    """Total in-band YES-BUY shares with yes_price >= p (takers who would lift a resting offer at price p)."""
    return sum(sz for (_, sz, q) in arrivals if q >= p - 1e-9)


def simulate_fill(arrivals, p, phi, S):
    """Rest SELL YES, size S shares, ask price p, capturing fraction phi of eligible arriving flow.

    Returns (fill_shares, fill_fraction, fully_filled, fill_time_frac_or_None).
    fill_time_frac: fraction of the first-half window elapsed when the order completes (None if not fully filled).
    """
    target = S
    cum = 0.0
    fill_time = None
    for (tf, sz, q) in arrivals:
        if q < p - 1e-9:
            continue                      # this taker would not pay our ask
        cum += phi * sz
        if fill_time is None and cum >= target:
            fill_time = tf
            break
    fill_shares = min(S, cum) if fill_time is None else float(S)
    # if never reached target, fill_shares = min(S, total captured)
    if fill_time is None:
        cap = phi * eligible_base(arrivals, p)
        fill_shares = min(S, cap)
    return fill_shares, fill_shares / S, (1.0 if fill_time is not None else 0.0), fill_time


# ============================================================ Cox proportional-hazards (own implementation)
def _cox_grad_hess_ll(Xo, eo, beta, l2):
    """Breslow gradient, Hessian, and ridge-penalized partial log-likelihood at beta.
    Xo/eo are pre-sorted by DESCENDING time so cumsum builds the risk set."""
    n, d = Xo.shape
    eta = np.clip(Xo @ beta, -30.0, 30.0)
    w = np.exp(eta)
    cw = np.cumsum(w)
    cwx = np.cumsum(w[:, None] * Xo, axis=0)
    cwxx = np.cumsum(w[:, None, None] * (Xo[:, :, None] * Xo[:, None, :]), axis=0)
    grad = np.zeros(d); hess = np.zeros((d, d)); ll = 0.0
    ev = eo == 1.0
    for i in np.nonzero(ev)[0]:
        r = cw[i]
        if r <= 0:
            continue
        mu = cwx[i] / r
        grad += Xo[i] - mu
        hess -= (cwxx[i] / r - np.outer(mu, mu))
        ll += eta[i] - math.log(r)
    grad -= l2 * beta
    hess -= l2 * np.eye(d)
    ll -= 0.5 * l2 * float(beta @ beta)
    return grad, hess, ll


def cox_ph_fit(X, times, events, l2=2.0, iters=100, tol=1e-7):
    """Cox PH via Breslow partial-likelihood Newton-Raphson with step-halving (own code; numpy only).

    X: (n,d) standardized covariates. times: event/censoring time. events: 1=event,0=censored.
    Ridge-penalized (l2) for stability. Returns (beta, baseline_cumhaz_fn, stats)."""
    X = np.asarray(X, float); times = np.asarray(times, float); events = np.asarray(events, float)
    n, d = X.shape
    order = np.argsort(-times)                        # descending time -> cumulative risk set
    Xo, eo = X[order], events[order]
    beta = np.zeros(d)
    _, _, ll = _cox_grad_hess_ll(Xo, eo, beta, l2)
    for _ in range(iters):
        grad, hess, ll = _cox_grad_hess_ll(Xo, eo, beta, l2)
        try:
            step = np.linalg.solve(hess - 1e-6 * np.eye(d), grad)   # H is neg-def; Newton = beta - H^-1 grad
        except np.linalg.LinAlgError:
            break
        # step-halving line search: accept only if the penalized log-likelihood improves
        lam = 1.0
        improved = False
        for _h in range(30):
            cand = beta - lam * step
            _, _, ll_c = _cox_grad_hess_ll(Xo, eo, cand, l2)
            if np.isfinite(ll_c) and ll_c >= ll:
                improved = True
                break
            lam *= 0.5
        if not improved:
            break
        if np.max(np.abs(cand - beta)) < tol:
            beta = cand
            break
        beta = cand
    # Breslow baseline cumulative hazard on ascending unique event times
    eta = X @ beta
    w = np.exp(eta)
    uniq = np.sort(np.unique(times[events == 1]))
    base = []
    for tt in uniq:
        d_t = np.sum((times == tt) & (events == 1))
        risk = np.sum(w[times >= tt])
        base.append(d_t / risk if risk > 0 else 0.0)
    cbase = np.cumsum(base)

    def H0(t):
        if len(uniq) == 0:
            return 0.0
        idx = np.searchsorted(uniq, t, side="right") - 1
        return cbase[idx] if idx >= 0 else 0.0

    return beta, H0, dict(uniq_times=uniq.tolist(), cbase=cbase.tolist())


def concordance_index(risk, times, events):
    """Harrell's C-index. risk = linear predictor (higher risk -> earlier event)."""
    risk = np.asarray(risk, float); times = np.asarray(times, float); events = np.asarray(events, float)
    conc = disc = tied = 0
    n = len(times)
    for i in range(n):
        if events[i] != 1:
            continue
        for j in range(n):
            if times[j] <= times[i]:
                continue                              # j must survive past i's event
            if risk[i] > risk[j]:
                conc += 1
            elif risk[i] < risk[j]:
                disc += 1
            else:
                tied += 1
    tot = conc + disc + tied
    return (conc + 0.5 * tied) / tot if tot > 0 else float("nan")


# ============================================================ simulation over the size / price / phi surface
def run_surface(data, sizes=SIZE_GRID, prices=PRICE_GRID, phis=None):
    """For every (order size, resting price, phi scenario), aggregate fill stats + captured PnL across
    ALL posted markets (the honest denominator: 74% of markets have zero in-band flow)."""
    if phis is None:
        phis = dict(PHI, theoretical=PHI_THEORETICAL_CEIL)
    N = len(data)
    surf = {}
    for sc, phi in phis.items():
        for p in prices:
            # precompute eligible base per market at this price
            base = np.array([phi * eligible_base(m["arrivals"], p) for m in data])
            outc = np.array([m["yes_outcome"] for m in data], float)
            edge_ct = p - outc                                     # maker edge per filled contract
            for S in sizes:
                fill_sh = np.minimum(S, base)
                frac = fill_sh / S
                any_fill = (base > 0).astype(float)
                full = (base >= S).astype(float)
                pnl = fill_sh * edge_ct
                surf[(sc, round(p, 2), S)] = dict(
                    scenario=sc, phi=phi, price=round(p, 2), size=S,
                    p_any_fill=float(np.mean(any_fill)),
                    p_full_fill=float(np.mean(full)),
                    exp_fill_frac=float(np.mean(frac)),
                    exp_fill_frac_given_any=float(np.mean(frac[any_fill > 0])) if any_fill.sum() else 0.0,
                    exp_fill_shares=float(np.mean(fill_sh)),
                    mean_captured_pnl_per_market=float(np.mean(pnl)),
                    total_captured_pnl=float(np.sum(pnl)),
                    n_markets=N)
    return surf


def weekly_capture(data, p, phi, S):
    """Per-resolution-week captured PnL (real outcomes) for resting size S at price p, capture phi.
    Returns (weekly_means_list, mean, week_clustered_t, worst_week_val, n_markets_posted_per_week_median)."""
    byw_pnl = defaultdict(float)
    byw_n = defaultdict(int)
    byw_shares = defaultdict(float)
    for m in data:
        b = phi * eligible_base(m["arrivals"], p)
        fill = min(S, b)
        byw_pnl[m["week"]] += fill * (p - m["yes_outcome"])
        byw_shares[m["week"]] += fill
        byw_n[m["week"]] += 1
    weeks = sorted(byw_pnl)
    vals = [byw_pnl[w] for w in weeks]
    mean = st.mean(vals) if vals else 0.0
    t = (mean / (st.stdev(vals) / math.sqrt(len(vals)))) if len(vals) >= 2 and st.stdev(vals) > 0 else float("nan")
    worst = min(vals) if vals else 0.0
    med_posted = st.median(list(byw_n.values())) if byw_n else 0
    mean_fill_shares = st.mean([byw_shares[w] for w in weeks]) if weeks else 0.0
    return vals, mean, t, worst, med_posted, dict(zip(weeks, vals)), mean_fill_shares


# ============================================================ reusable go-live estimator
class FillModel:
    """Reusable maker-fill-probability estimator for the go-live sizing layer.

    Two engines, both fit on the same real print reconstruction:
      * empirical  : the per-market eligible-flow distribution (ground truth; no model risk). Default.
      * cox        : Cox PH P(fill within window) as a smooth function of covariates (homerun-style),
                     for extrapolating to (size, feature) combos outside the empirical grid.
    fill_probability() returns pessimistic/realistic/optimistic estimates (the homerun 3-estimate ensemble),
    driven by the queue-capture knob phi.
    """

    def __init__(self, data):
        self.data = data
        # empirical eligible-flow arrays per resting price (shares of in-band YES-buy flow at yes_price>=p)
        self._elig = {}
        for p in PRICE_GRID:
            self._elig[round(p, 2)] = np.array([eligible_base(m["arrivals"], p) for m in data])
        self._median_window_hours = st.median([m["window_hours"] for m in data])
        self._cox = None

    # ---- empirical engine ----
    def _elig_array(self, price):
        pr = round(price, 2)
        if pr in self._elig:
            return self._elig[pr]
        return np.array([eligible_base(m["arrivals"], price) for m in self.data])

    def _empirical(self, order_size, price, phi):
        base = phi * self._elig_array(price)
        return dict(
            p_any_fill=float(np.mean(base > 0)),
            p_full_fill=float(np.mean(base >= order_size)),
            exp_fill_fraction=float(np.mean(np.minimum(order_size, base) / order_size)))

    # ---- Cox engine (fit lazily) ----
    def _covariates(self, m, order_size, price):
        base = eligible_base(m["arrivals"], price)
        arr_rate = base / max(m["window_hours"], 1e-6)
        return np.array([
            math.log1p(arr_rate),                       # trade intensity (eligible YES-buy shares/hr)
            math.log(order_size),                       # order size (bigger -> harder to fully fill)
            (price - BAND_LO) / (BAND_HI - BAND_LO),    # distance from band floor (touch aggressiveness)
            m["horizon_days"],                          # time-to-resolution (weekly horizon)
        ])

    def fit_cox(self, l2=2.0):
        """Fit Cox PH for 'time (window-fraction) until an order of a representative size is fully filled'.
        Trains on the realistic phi; the ensemble is obtained by proportional-hazards scaling in phi."""
        Xrows, times, events, covspec = [], [], [], []
        phi = PHI["realistic"]
        # use a representative training size per market drawn from the size grid to give size variation
        rng = np.random.default_rng(7)
        for m in self.data:
            for S in (10, 50, 250):
                _, _, full, tfill = simulate_fill(m["arrivals"], OPERATING_PRICE, phi, S)
                Xrows.append(self._covariates(m, S, OPERATING_PRICE))
                if full > 0 and tfill is not None:
                    times.append(max(tfill, 1e-3)); events.append(1.0)
                else:
                    times.append(1.0); events.append(0.0)   # censored at window end (not filled)
        X = np.array(Xrows)
        mu, sd = X.mean(0), X.std(0) + 1e-9
        Xs = (X - mu) / sd
        beta, H0, stats = cox_ph_fit(Xs, times, events, l2=l2)
        risk = Xs @ beta
        cidx = concordance_index(risk, times, events)
        # Brier at window end (t=1.0): predicted P(filled by end) vs observed event
        H_end = H0(1.0)
        pred = 1.0 - np.exp(-H_end * np.exp(risk))
        obs = np.array(events)
        brier = float(np.mean((pred - obs) ** 2))
        self._cox = dict(beta=beta, H0=H0, mu=mu, sd=sd, cindex=cidx, brier=brier,
                         cov_names=["log_arrival_rate", "log_order_size", "dist_from_floor", "horizon_days"])
        return self._cox

    def _cox_prob(self, m, order_size, price, phi, t_frac=1.0):
        if self._cox is None:
            self.fit_cox()
        c = self._cox
        x = (self._covariates(m, order_size, price) - c["mu"]) / c["sd"]
        lp = float(x @ c["beta"])
        # proportional-hazards scaling by capture fraction phi (relative to the realistic-phi training)
        scale = phi / PHI["realistic"]
        H = c["H0"](t_frac) * math.exp(lp) * scale
        return 1.0 - math.exp(-H)

    def cox_probability(self, order_size, price=OPERATING_PRICE, phi=None, t_frac=1.0):
        if phi is None:
            phi = PHI["realistic"]
        ps = [self._cox_prob(m, order_size, price, phi, t_frac) for m in self.data]
        return float(np.mean(ps))

    # ---- public API ----
    def fill_probability(self, order_size, features=None, engine="empirical"):
        """MAIN reusable entry point for the sizing layer.

        order_size : shares of YES you intend to rest as a SELL.
        features   : optional dict; supported key 'price' (resting ask, default OPERATING_PRICE).
                     ('arrival_rate','horizon_days' accepted for the cox engine but the empirical engine
                      already integrates over the real market-level distribution of those.)
        engine     : 'empirical' (default, ground-truth) or 'cox' (smooth homerun-style extrapolator).

        Returns {pessimistic, realistic, optimistic} each a dict with p_any_fill, p_full_fill,
        exp_fill_fraction -- the homerun-style 3-estimate ensemble (driven by queue-capture phi).
        """
        features = features or {}
        price = float(features.get("price", OPERATING_PRICE))
        out = {}
        for sc, phi in PHI.items():
            if engine == "cox":
                pf = self.cox_probability(order_size, price=price, phi=phi)
                out[sc] = dict(p_full_fill=round(pf, 4),
                               p_any_fill=round(self._empirical(order_size, price, phi)["p_any_fill"], 4),
                               exp_fill_fraction=round(self._empirical(order_size, price, phi)["exp_fill_fraction"], 4))
            else:
                e = self._empirical(order_size, price, phi)
                out[sc] = {k: round(v, 4) for k, v in e.items()}
        return out


# ============================================================ report + summary
def _fmt_pct(x):
    return f"{100*x:.1f}%"


def main():
    t0 = time.time()
    print("[1/5] reconstructing in-band YES-buy arrival processes from real prints (cached) ...")
    data = reconstruct_arrivals()
    N = len(data)
    nq = sum(1 for m in data if m["ib_shares"] > 0)
    print(f"      {N} posted weekly markets; {nq} ({nq/N:.0%}) have >0 in-band first-half YES-buy flow")

    print("[2/5] building fill surface over size x price x phi ...")
    surf = run_surface(data)

    print("[3/5] weekly-capture curves ...")
    # capture $/week vs order size at OPERATING_PRICE for each scenario (incl. theoretical ceiling)
    cap_curves = {}
    for sc, phi in dict(PHI, theoretical=PHI_THEORETICAL_CEIL).items():
        rows = []
        for S in SIZE_GRID:
            vals, mean, tt, worst, medn, _, _fs = weekly_capture(data, OPERATING_PRICE, phi, S)
            rows.append(dict(size=S, mean_week_usd=round(mean, 2),
                             week_t=round(tt, 3) if not math.isnan(tt) else None,
                             worst_week_usd=round(worst, 2)))
        cap_curves[sc] = rows

    # price frontier at a fixed mid size (S=100) -> edge/ct and $/week vs resting price
    price_frontier = {}
    for sc, phi in PHI.items():
        rows = []
        for p in PRICE_GRID:
            vals, mean, tt, worst, medn, _, _fs = weekly_capture(data, p, phi, 100)
            # per-contract realized captured edge = mean over filled contracts of (p - outcome)
            base = np.array([phi * eligible_base(m["arrivals"], p) for m in data])
            fill = np.minimum(100, base)
            tot_fill = fill.sum()
            edge_ct = (np.sum(fill * np.array([p - m["yes_outcome"] for m in data])) / tot_fill) if tot_fill > 0 else 0.0
            rows.append(dict(price=round(p, 2), mean_week_usd=round(mean, 2),
                             realized_edge_per_ct=round(float(edge_ct), 4),
                             weekly_fill_shares=round(float(tot_fill) / len(set(m["week"] for m in data)), 1)))
        price_frontier[sc] = rows

    # phi sensitivity: realistic weekly $ at S=100, p=OPERATING_PRICE across phi
    phi_sens = []
    for phi in PHI_SENS:
        vals, mean, tt, worst, medn, _, _fs = weekly_capture(data, OPERATING_PRICE, phi, 100)
        phi_sens.append(dict(phi=phi, mean_week_usd=round(mean, 2),
                             week_t=round(tt, 3) if not math.isnan(tt) else None,
                             worst_week_usd=round(worst, 2)))

    print("[4/5] fitting Cox PH fill model (own Breslow-Newton) ...")
    fm = FillModel(data)
    cox = fm.fit_cox()
    # hazard ratios (per 1 SD of standardized covariate)
    hr = {name: round(math.exp(b), 3) for name, b in zip(cox["cov_names"], cox["beta"])}

    # fill-probability curve vs size (headline, empirical engine, 3 scenarios) at OPERATING_PRICE
    fillprob_curve = []
    for S in SIZE_GRID:
        row = dict(size=S)
        est = fm.fill_probability(S, features={"price": OPERATING_PRICE})
        for sc in ("pessimistic", "realistic", "optimistic"):
            row[sc] = est[sc]
        fillprob_curve.append(row)

    # cross-check: cox engine vs empirical at a few sizes
    cox_vs_emp = []
    for S in (10, 100, 1000):
        e = fm.fill_probability(S, {"price": OPERATING_PRICE}, engine="empirical")["realistic"]
        cx = fm.fill_probability(S, {"price": OPERATING_PRICE}, engine="cox")["realistic"]
        cox_vs_emp.append(dict(size=S, empirical_p_full=e["p_full_fill"], cox_p_full=cx["p_full_fill"]))

    # ---- capacity-binding + bankroll mapping ----
    n_weeks = len(set(m["week"] for m in data))
    med_posted = st.median([sum(1 for m in data if m["week"] == w) for w in set(m["week"] for m in data)])
    # theoretical max weekly capture (phi=1, p=OPERATING_PRICE, unbounded size)
    _, maxcap_mean, _, _, _, _, _ = weekly_capture(data, OPERATING_PRICE, PHI_THEORETICAL_CEIL, 10**9)
    _, realcap_ceiling, _, _, _, _, realcap_ceiling_shares = weekly_capture(data, OPERATING_PRICE, PHI["realistic"], 10**9)

    # Capital model: a RESTING order ties up collateral only when it FILLS. Selling 1 YES at price p needs
    # (1-p) collateral, held to resolution (~1 week). So required capital ~= weekly FILLED collateral =
    # weekly_fill_shares * (1-p). We invert: for a bankroll B, find the per-market size S whose realized weekly
    # filled collateral equals B (capped where flow-capacity binds, i.e. S -> infinity still under-uses B).
    coll_per_share = 1.0 - OPERATING_PRICE
    phi_r = PHI["realistic"]

    def week_usd_and_capital(S, phi):
        _, mean, _, worst, _, _, fill_sh = weekly_capture(data, OPERATING_PRICE, phi, S)
        return mean, worst, fill_sh * coll_per_share      # weekly $, worst week $, capital tied (collateral)

    def size_for_bankroll(B, phi):
        # binary-search per-market size so weekly filled collateral ~= B; cap if capacity binds first
        _, _, cap_ceil = week_usd_and_capital(10**9, phi)
        if cap_ceil <= B:
            return None, cap_ceil                          # capacity-bound: any size fits under bankroll
        lo, hi = 0.0, 1e7
        for _ in range(60):
            mid = 0.5 * (lo + hi)
            _, _, capm = week_usd_and_capital(mid, phi)
            if capm < B:
                lo = mid
            else:
                hi = mid
        return 0.5 * (lo + hi), B

    bankrolls = [50, 100, 250, 500, 2000, 10000, 50000]
    bankroll_rows = []
    for B in bankrolls:
        # size the book on the REALISTIC (central) phi, then evaluate all three phi at that SAME size,
        # so the ensemble is monotone (opt >= real >= pess) and not confounded by size choice.
        S_per, capital = size_for_bankroll(B, phi_r)
        Suse = 10**9 if S_per is None else S_per
        row = dict(bankroll=B,
                   realistic_shares_per_market=("capacity-bound" if S_per is None else round(S_per, 2)),
                   realistic_capital_used=round(capital, 2))
        for sc, phi in PHI.items():
            wk, worst, _ = week_usd_and_capital(Suse, phi)
            row[f"{sc}_week_usd"] = round(wk, 2)
            if sc == "realistic":
                row["realistic_worst_week_usd"] = round(worst, 2)
        bankroll_rows.append(row)

    small_usd = bankroll_rows[[r["bankroll"] for r in bankroll_rows].index(500)]["realistic_week_usd"]
    large_usd = realcap_ceiling            # realistic-phi capacity ceiling (size unbounded)
    capital_to_saturate_realistic = realcap_ceiling_shares * coll_per_share

    # fraction of the +0.12/ct edge captured (per-contract at operating point) and capacity utilization
    base_op = np.array([PHI["realistic"] * eligible_base(m["arrivals"], OPERATING_PRICE) for m in data])
    fill_op = np.minimum(100, base_op)
    tot = fill_op.sum()
    realized_edge_op = float(np.sum(fill_op * np.array([OPERATING_PRICE - m["yes_outcome"] for m in data])) / tot) if tot > 0 else 0.0
    frac_edge_per_ct = realized_edge_op / 0.12

    print("[5/5] writing outputs ...")
    summary = dict(
        generated=datetime.now(timezone.utc).isoformat(),
        n_posted_markets=N, n_with_inband_flow=nq, frac_with_flow=round(nq / N, 4),
        n_weeks=n_weeks, median_markets_posted_per_week=med_posted,
        assumptions=dict(
            phi_definition="phi = fraction of eligible arriving in-band YES-buy flow the resting seller captures "
                           "(queue-competition proxy; UNOBSERVABLE without L2 queue data).",
            phi_scenarios=PHI, phi_theoretical_ceiling=PHI_THEORETICAL_CEIL,
            operating_price=OPERATING_PRICE,
            resting_price_note="Seller rests SELL YES at ask=operating_price; only in-band YES-buy takers "
                               "paying >= ask can lift the offer (edge-vs-capacity frontier).",
            no_l2="No L2 queue history on Polymarket public data; queue depth is unobservable and is collapsed "
                  "into phi. This is a proxy for homerun's full-queue Cox model.",
            thin_n=f"median ~6 in-band prints per fillable market -> per-market time-to-fill is granular; "
                   f"aggregate over {N} markets / {n_weeks} weeks is robust."),
        fill_probability_curve=fillprob_curve,
        capture_curves_usd_per_week=cap_curves,
        price_frontier=price_frontier,
        phi_sensitivity=phi_sens,
        cox=dict(hazard_ratios_per_sd=hr, c_index=round(cox["cindex"], 4), brier=round(cox["brier"], 4),
                 cov_names=cox["cov_names"], beta=[round(float(b), 4) for b in cox["beta"]],
                 note="Own Breslow partial-likelihood Newton fit; HR>1 => covariate raises the fill hazard "
                      "(faster/more-likely fill). Event=order fully filled within first-half window."),
        cox_vs_empirical=cox_vs_emp,
        capacity=dict(
            median_markets_posted_per_week=med_posted,
            theoretical_max_week_usd_phi1=round(maxcap_mean, 2),
            realistic_capacity_ceiling_week_usd=round(realcap_ceiling, 2),
            capital_to_saturate_realistic_usd=round(capital_to_saturate_realistic, 2),
            bankroll_to_weekly_usd=bankroll_rows,
            collateral_per_share=round(coll_per_share, 3),
            capital_note="Resting orders consume collateral only when filled; a bankroll B funds up to B of "
                         "weekly FILLED collateral. Beyond the capital that saturates realized flow, extra "
                         "capital cannot be deployed (capacity-bound)."),
        headline=dict(
            small_bankroll_realistic_usd_per_week=round(small_usd, 2),
            large_size_realistic_ceiling_usd_per_week=round(large_usd, 2),
            realized_edge_per_ct_at_operating_point=round(realized_edge_op, 4),
            fraction_of_0p12_edge_captured_per_ct=round(frac_edge_per_ct, 3)),
    )
    with open(SUMMARY, "w") as f:
        json.dump(summary, f, indent=2, default=str)
    write_report(summary)
    print(f"[done] {time.time()-t0:.0f}s -> fill_model_report.md, fill_model_summary.json")
    return summary, fm


